"""Local evaluation against the public pack.

Miners run the same sandbox, the same tools and the same scorer the engine runs,
against instances generated by the same code from a published seed. That is the
whole point of publishing the generator rather than the data: composition search
is only possible if a miner can measure a candidate without submitting it, and a
measurement that used a different harness would not predict anything.

What a miner cannot reproduce is the hidden draw. Local scores predict; they do
not decide.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass, field
from pathlib import Path

from capability_subnet.backend.scorer.aggregate import (
    EfficiencyInputs,
    aggregate_scores,
    measure_resources,
    valid_rows,
)
from capability_subnet.backend.scorer.retention import (
    ProbeOutcome,
    build_probe,
    relative_retention,
    run_probe,
)
from capability_subnet.common.schemas import CandidateScores, InstanceResult, Recipe
from capability_subnet.merge_engine.engine import reconstruct
from capability_subnet.merge_engine.loader import SafetensorsAdapterSource
from capability_subnet.registry.snapshot import PoolSnapshot, load_snapshot
from capability_subnet.sandbox.model_client import ModelClient
from capability_subnet.sandbox.orchestrator import SandboxConfig, run_batch
from capability_subnet.workflows import get_workflow

#: Probe seed for local runs. Fixed and public: the engine draws its own from a
#: secret root per window, so there is nothing here for a miner to tune against
#: and no reason to hide it.
LOCAL_PROBE_SEED = 20260729


def probe_base_model(client: ModelClient, probe_seed: int | None = None) -> ProbeOutcome:
    """Measure the unmodified base model on the probe.

    Run this once against an endpoint serving the base model with no adapter,
    then pass the result to :func:`evaluate_locally`. Without it the retention
    component reads as a flat 1.0 and a package that has quietly lost general
    instruction-following looks fine right up until the engine says otherwise.
    """
    return run_probe(
        client, build_probe(probe_seed if probe_seed is not None else LOCAL_PROBE_SEED)
    )


log = logging.getLogger(__name__)


@dataclass(slots=True)
class LocalResult:
    """What a local evaluation produced."""

    recipe_sha256: str
    artifact_sha256: str
    artifact_bytes: int
    scores: CandidateScores
    hidden_results: list[InstanceResult] = field(default_factory=list)
    ood_results: list[InstanceResult] = field(default_factory=list)

    def summary(self) -> str:
        valid = len(valid_rows(self.hidden_results))
        stage_lines = "\n".join(
            f"    {stage:<24} {value:.3f}"
            for stage, value in sorted(self.scores.per_stage_means.items())
        )
        return (
            f"recipe    : {self.recipe_sha256[:19]}…\n"
            f"artifact  : {self.artifact_sha256[:19]}… ({self.artifact_bytes / 1024 / 1024:.0f} MB)\n"
            f"instances : {valid} scored of {len(self.hidden_results)} attempted\n"
            f"end-to-end: {self.scores.end_to_end:.3f}\n"
            f"balance   : {self.scores.stage_balance:.3f}\n"
            f"ood       : {self.scores.ood:.3f}\n"
            f"qualified : {self.scores.qualified_score:.3f}\n"
            f"per stage :\n{stage_lines}"
        )


def build_local_artifact(
    recipe: Recipe,
    *,
    pool_dir: str | Path,
    output_dir: str | Path,
    snapshot: PoolSnapshot | None = None,
) -> tuple[str, int, Path]:
    """Reconstruct a recipe locally.

    Uses the same engine the evaluation backend uses, so the artifact digest a
    miner sees here is the digest the engine will compute. A mismatch means the
    two hosts disagree about determinism, which is worth knowing before
    committing rather than after.
    """
    pool = snapshot or load_snapshot()
    source = SafetensorsAdapterSource(pool_dir)
    result = reconstruct(recipe, pool, source, output_dir=output_dir)
    return result.artifact_sha256, result.size_bytes, Path(output_dir)


def evaluate_locally(
    recipe: Recipe,
    client: ModelClient,
    *,
    pool_dir: str | Path,
    artifact_dir: str | Path,
    instance_count: int = 30,
    ood_count: int = 10,
    pack_seed: int | None = None,
    snapshot: PoolSnapshot | None = None,
    sandbox_config: SandboxConfig | None = None,
    probe_seed: int | None = None,
    base_probe: ProbeOutcome | None = None,
) -> LocalResult:
    """Reconstruct a recipe and score it on public instances.

    Args:
        client: a model endpoint serving the reconstructed package. Standing that
            up is the miner's job — this function does not assume a serving stack.
        instance_count: how many public instances to run. Fewer is faster; the
            variance of an end-to-end rate over twenty instances is wide enough
            that small differences between two recipes will not be visible.
        probe_seed: seed for the general-capability probe. Any value works
            locally; the engine draws its own from a secret root per window, so
            matching it is neither possible nor useful.
        base_probe: the base model's outcome on the same probe. Without it the
            retention component reads as 1.0, which is optimistic — the engine
            measures the base every window and will not be. Measure the base
            model once with :func:`probe_base_model` and pass the result in.
    """
    import random

    from capability_subnet.workflows.industrial_maintenance_de_v1.public_pack import (
        PUBLIC_OOD_SEED,
        PUBLIC_PACK_SEED,
    )

    pool = snapshot or load_snapshot()
    workflow = get_workflow(pool.registry.workflow_id)

    artifact_sha256, artifact_bytes, _ = build_local_artifact(
        recipe, pool_dir=pool_dir, output_dir=artifact_dir, snapshot=pool
    )

    hidden_rng = random.Random(pack_seed if pack_seed is not None else PUBLIC_PACK_SEED)
    ood_rng = random.Random(PUBLIC_OOD_SEED)

    from capability_subnet.workflows.industrial_maintenance_de_v1.generator import sample_seeds

    hidden = [
        workflow.generate_instance(seed, split="public")
        for seed in sample_seeds(hidden_rng, instance_count)
    ]
    ood = [
        workflow.generate_instance(seed, split="ood") for seed in sample_seeds(ood_rng, ood_count)
    ]

    config = sandbox_config or SandboxConfig()
    probe_items = build_probe(probe_seed if probe_seed is not None else LOCAL_PROBE_SEED)
    hidden_results = [outcome.result for outcome in run_batch(hidden, client, config=config)]
    ood_results = (
        [outcome.result for outcome in run_batch(ood, client, config=config)] if ood else []
    )

    resources = measure_resources(
        hidden_results, artifact_bytes=artifact_bytes, peak_vram_gb=config.peak_vram_gb
    )

    probe = run_probe(client, probe_items)
    retention = relative_retention(probe, base_probe) if base_probe is not None else 1.0

    scores = aggregate_scores(
        hidden_results,
        ood_results,
        workflow.critical_axes,
        retention=retention,
        efficiency=EfficiencyInputs(
            artifact_bytes=artifact_bytes,
            peak_vram_gb=config.peak_vram_gb,
            reference_seconds=resources.mean_workflow_seconds,
        ),
    )

    return LocalResult(
        recipe_sha256=recipe.digest(),
        artifact_sha256=artifact_sha256,
        artifact_bytes=artifact_bytes,
        scores=scores,
        hidden_results=hidden_results,
        ood_results=ood_results,
    )
